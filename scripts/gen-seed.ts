/* Prints supabase/seed.sql from the reference constants. Run: npm run seed:sql */
import { seedLibrary } from "../lib/seedLibrary.ts";

const q = (v: unknown): string => {
  if (v == null) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  if (Array.isArray(v)) return `array[${v.map(q).join(",")}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const lib = seedLibrary();
const out: string[] = ["-- Generated by scripts/gen-seed.ts from content/library.ts. Do not edit by hand.", "begin;"];

out.push("insert into public.projects (slug, title, lede, services, year, tags, palette, url, sort) values");
out.push(lib.projects.map(p => `  (${[p.slug, p.title, p.lede, p.services, p.year].map(q).join(", ")}, ${q(p.tags)}, ${q(p.palette)}, ${q(p.url)}, ${p.sort})`).join(",\n")
  + "\non conflict (slug) do nothing;");

out.push("insert into public.team_members (name, role, sort) values");
out.push(lib.team.map(t => `  (${q(t.name)}, ${q(t.role)}, ${t.sort})`).join(",\n") + ";");

out.push("insert into public.companies (name, url, figure, show_in_clients, sort) values");
out.push(lib.companies.map(c => `  (${q(c.name)}, ${q(c.url)}, ${q(c.figure)}, ${c.showInClients}, ${c.sort})`).join(",\n")
  + "\non conflict (name) do nothing;");

const byId = Object.fromEntries(lib.companies.map(c => [c.id, c.name]));
out.push("insert into public.testimonials (company_id, kind, quote, name, name_url, role, sort)");
out.push(lib.testimonials.map(t => `  select id, ${q(t.kind)}, ${q(t.quote)}, ${q(t.name)}, ${q(t.nameUrl)}, ${q(t.role)}, ${t.sort} from public.companies where name = ${q(byId[t.companyId])}`).join("\n  union all\n") + ";");

out.push("commit;");
console.log(out.join("\n"));
